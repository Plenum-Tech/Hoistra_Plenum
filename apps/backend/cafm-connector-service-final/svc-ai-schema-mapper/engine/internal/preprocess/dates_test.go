package preprocess

import "testing"

// Expectations from pandas 2.3.3: guess_datetime_format(s, dayfirst=True), to_datetime(format=
// "ISO8601") and to_datetime(format=…), errors="coerce" ("" = no guess / NaT).

func TestTheDayFirstGuessIsPandas(t *testing.T) {
	cases := map[string]string{
		"10/07/2026 14:30":              "%d/%m/%Y %H:%M",
		"07/13/2026":                    "%m/%d/%Y",
		"2026/07/10 14:30:00":           "%Y/%d/%m %H:%M:%S",
		"2026/07/13":                    "%Y/%m/%d",
		"31 Dec 2025":                   "%d %b %Y",
		"Dec 31, 2025":                  "%b %d, %Y",
		"31-Dec-2025":                   "%d-%b-%Y",
		"31 December 2025":              "%d %B %Y",
		"10.07.2026":                    "%d.%m.%Y",
		"10/07/26":                      "",
		"10/07/2026 2:30 PM":            "",
		"DEC 31, 2025":                  "",
		"10/07/2014 20:14":              "",
		"10/07/2026 14:30:00.5":         "%d/%m/%Y %H:%M:%S.%f",
		"5/1/2026":                      "%d/%m/%Y",
		"1/2/2026":                      "%d/%m/%Y",
		"13/13/2026":                    "",
		"45/01/2026":                    "",
		"10-07-2026 9:05":               "%d-%m-%Y %H:%M",
		"2026-07-10 14:30":              "%Y-%d-%m %H:%M",
		"2026.07.10":                    "%Y.%d.%m",
		"31 Sept 2025":                  "",
		"10/07/2026 24:00":              "",
		"10/07/2026 14:30:00.123456789": "%d/%m/%Y %H:%M:%S.%f",
		"2026/13/01":                    "%Y/%d/%m",
		"30/02/2026":                    "",
		"10/07/0999":                    "",
	}
	for s, want := range cases {
		got, ok := guessDayfirst(s)
		if !ok {
			got = ""
		}
		if got != want {
			t.Errorf("%q: %q, want %q", s, got, want)
		}
	}
}

func TestTheISOParserIsPandas(t *testing.T) {
	cases := map[string]string{
		"2026-07-10":                       "2026-07-10T00:00:00",
		" 2026-07-10 ":                     "",
		"2026-7-1":                         "2026-07-01T00:00:00",
		"2026/07/10":                       "2026-07-10T00:00:00",
		"2026.07.10":                       "2026-07-10T00:00:00",
		"2026 07 10":                       "2026-07-10T00:00:00",
		"2026\\07\\10":                     "2026-07-10T00:00:00",
		"20260710":                         "2026-07-10T00:00:00",
		"2026071":                          "",
		"202607":                           "",
		"2026":                             "2026-01-01T00:00:00",
		"2026-07":                          "2026-07-01T00:00:00",
		"2026-07-10T14":                    "2026-07-10T14:00:00",
		"2026-07-10T1":                     "",
		"2026-07-10 14:30":                 "2026-07-10T14:30:00",
		"2026-07-10T14:3":                  "2026-07-10T14:03:00",
		"2026-07-10T1430":                  "2026-07-10T14:30:00",
		"2026-07-10T143000":                "2026-07-10T14:30:00",
		"2026-07-10T14:30:00.123456789123": "2026-07-10T14:30:00.123456789",
		"2026-07-10T14:30:00.5 ":           "2026-07-10T14:30:00.500000",
		"2026-07-10T24:00":                 "",
		"2026-02-30":                       "",
		"1600-01-01":                       "",
		"2263-01-01":                       "",
		"-2026-01-01":                      "",
		"2026-07-10x":                      "",
		"2026-07-10 ":                      "",
		"2026-07-10T":                      "",
		"2026-7-10 9:5:3":                  "2026-07-10T09:05:03",
	}
	for s, want := range cases {
		got := ""
		if st, ok, tz := parseISO(s); ok && !tz {
			got = st.iso()
		}
		if got != want {
			t.Errorf("%q: %q, want %q", s, got, want)
		}
	}
	if _, _, tz := parseISO("2026-07-10T14:30:00Z"); !tz {
		t.Error("a time zone is left to Python")
	}
}

func TestStrptimeIsPandas(t *testing.T) {
	for _, c := range []struct{ format, value, want string }{
		{"%d/%m/%Y", "1/2/2026", "2026-02-01T00:00:00"},
		{"%d/%m/%Y", " 1/02/2026", "2026-02-01T00:00:00"},
		{"%d/%m/%Y", "01/2/2026 ", ""},
		{"%Y-%m-%d", "2026-1-5", "2026-01-05T00:00:00"},
		{"%Y-%m-%d", "2025-12- 1", "2025-12-01T00:00:00"},
		{"%Y-%m-%d", "\u0662\u0660\u0662\u0665-\u0660\u0661-\u0660\u0661", ""},
		{"%Y-%m-%d", "\u0662\u0660\u0662\u0665-1-1", "2025-01-01T00:00:00"},
		{"%d/%m/%Y", "1\u0663/01/2026", "2026-01-13T00:00:00"},
		{"%d/%m/%Y", "31/04/2026", ""},
		{"%d/%m/%Y", "29/02/2025", ""},
		{"%d/%m/%Y", "01/01/1600", ""},
		{"%d %b %Y", "1 DEC 2025", "2025-12-01T00:00:00"},
		{"%d %b %Y", "1  Dec\x092025", "2025-12-01T00:00:00"},
		{"%d/%m/%Y %H:%M", "10/07/2026 9:5", "2026-07-10T09:05:00"},
		{"%d/%m/%Y %H:%M:%S.%f", "10/07/2026 14:30:00.123456789", "2026-07-10T14:30:00.123456789"},
		{"%Y-%m-%d", "0000-01-01", ""},
	} {
		got := ""
		if st, ok, _ := strptime(c.value, c.format); ok {
			got = st.iso()
		}
		if got != c.want {
			t.Errorf("%s %q: %q, want %q", c.format, c.value, got, c.want)
		}
	}
	if _, _, leap := strptime("10/07/2026 14:30:60", "%d/%m/%Y %H:%M:%S"); !leap {
		t.Error("a 60th second is left to Python (pandas rolls it into the next minute)")
	}
}
