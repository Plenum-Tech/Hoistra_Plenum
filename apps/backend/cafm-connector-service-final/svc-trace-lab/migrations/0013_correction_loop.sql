-- 0013_correction_loop.sql (3 Nov 2026): the correction loop of the review page. Traces, then human notes, then failure
-- modes, then the answer specification (SPEC.md), then the prompt, skill or code correction, then regression runs, then
-- a rerun. A coding agent may PROPOSE a failure mode, a label or an expected answer by writing rows (ops/CODING_AGENT.md);
-- a proposal counts only once a person approves it (lab_reviews: one final decision per proposal). Expected answers of a
-- regression run come from the approved specification and the company records, never from an answer the model gave.
-- What the browser saw of each answer (lab_frontend_events) is kept beside the recorded backend trace. Every new table is
-- append-only. Runs in Trace Lab OWN database. Applied only by migrate.apply_pending. A correction is a new numbered file.
SET LOCAL lock_timeout = '3s';

ALTER TABLE tracelab.lab_runs DROP CONSTRAINT lab_runs_source_check;

ALTER TABLE tracelab.lab_runs ADD CONSTRAINT lab_runs_source_check
    CHECK (source IN ('sync','coding_agent','excel','manual','regression'));

ALTER TABLE tracelab.lab_questions DROP CONSTRAINT lab_questions_source_check;

ALTER TABLE tracelab.lab_questions ADD CONSTRAINT lab_questions_source_check
    CHECK (source IN ('sync','coding_agent','excel','manual','regression'));

CREATE TABLE tracelab.lab_reviews (
    id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    subject_kind      text        NOT NULL CHECK (subject_kind IN ('failure_mode','expected_answer','spec_version')),
    subject_id        uuid        NOT NULL,
    decision          text        NOT NULL CHECK (decision IN ('approved','rejected')),
    note              text        CHECK (note IS NULL OR char_length(note) <= 2000),
    reviewer_id       uuid        NOT NULL,
    reviewer_email    text        CHECK (reviewer_email IS NULL OR char_length(reviewer_email) <= 320),
    reviewer_role     text        CHECK (reviewer_role IS NULL OR char_length(reviewer_role) <= 40),
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ux_tl_lab_reviews_subject UNIQUE (subject_kind, subject_id)
);

CREATE TRIGGER lab_reviews_append_only BEFORE UPDATE OR DELETE ON tracelab.lab_reviews
    FOR EACH ROW EXECUTE FUNCTION tracelab.refuse_change();

CREATE TRIGGER lab_reviews_no_truncate BEFORE TRUNCATE ON tracelab.lab_reviews
    FOR EACH STATEMENT EXECUTE FUNCTION tracelab.refuse_change();

CREATE TABLE tracelab.lab_spec_versions (
    id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    version_no        integer     GENERATED BY DEFAULT AS IDENTITY,
    intro             text        CHECK (intro IS NULL OR char_length(intro) <= 20000),
    rules             jsonb       NOT NULL CHECK (jsonb_typeof(rules) = 'array'),
    body              text        NOT NULL CHECK (char_length(body) BETWEEN 1 AND 200000),
    based_on          uuid,
    source            text        NOT NULL CHECK (source IN ('manual','coding_agent')),
    created_by        uuid,
    created_by_email  text        CHECK (created_by_email IS NULL OR char_length(created_by_email) <= 320),
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ux_tl_lab_spec_versions_no UNIQUE (version_no)
);

CREATE TRIGGER lab_spec_versions_append_only BEFORE UPDATE OR DELETE ON tracelab.lab_spec_versions
    FOR EACH ROW EXECUTE FUNCTION tracelab.refuse_change();

CREATE TRIGGER lab_spec_versions_no_truncate BEFORE TRUNCATE ON tracelab.lab_spec_versions
    FOR EACH STATEMENT EXECUTE FUNCTION tracelab.refuse_change();

CREATE TABLE tracelab.lab_corrections (
    id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    mode_lineage_id   uuid,
    spec_rule         text        CHECK (spec_rule IS NULL OR char_length(spec_rule) BETWEEN 1 AND 40),
    kind              text        NOT NULL CHECK (kind IN ('prompt','skill','code','data','spec')),
    reference         text        NOT NULL CHECK (char_length(reference) BETWEEN 1 AND 500),
    description       text        CHECK (description IS NULL OR char_length(description) <= 2000),
    source            text        NOT NULL CHECK (source IN ('manual','coding_agent')),
    created_by        uuid,
    created_by_email  text        CHECK (created_by_email IS NULL OR char_length(created_by_email) <= 320),
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_tl_lab_corrections_target CHECK (mode_lineage_id IS NOT NULL OR spec_rule IS NOT NULL)
);

CREATE INDEX ix_tl_lab_corrections_mode ON tracelab.lab_corrections (mode_lineage_id, created_at DESC);

CREATE TRIGGER lab_corrections_append_only BEFORE UPDATE OR DELETE ON tracelab.lab_corrections
    FOR EACH ROW EXECUTE FUNCTION tracelab.refuse_change();

CREATE TRIGGER lab_corrections_no_truncate BEFORE TRUNCATE ON tracelab.lab_corrections
    FOR EACH STATEMENT EXECUTE FUNCTION tracelab.refuse_change();

CREATE TABLE tracelab.lab_regression_runs (
    id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    run_id            uuid        NOT NULL REFERENCES tracelab.lab_runs (id),
    mode_lineage_id   uuid        NOT NULL,
    spec_version_id   uuid        REFERENCES tracelab.lab_spec_versions (id),
    spec_rule         text        CHECK (spec_rule IS NULL OR char_length(spec_rule) BETWEEN 1 AND 40),
    space             text        NOT NULL CHECK (char_length(space) BETWEEN 1 AND 40),
    created_by        uuid,
    created_by_email  text        CHECK (created_by_email IS NULL OR char_length(created_by_email) <= 320),
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ux_tl_lab_regression_runs_run UNIQUE (run_id)
);

CREATE INDEX ix_tl_lab_regression_runs_mode ON tracelab.lab_regression_runs (mode_lineage_id, created_at DESC);

CREATE TRIGGER lab_regression_runs_append_only BEFORE UPDATE OR DELETE ON tracelab.lab_regression_runs
    FOR EACH ROW EXECUTE FUNCTION tracelab.refuse_change();

CREATE TRIGGER lab_regression_runs_no_truncate BEFORE TRUNCATE ON tracelab.lab_regression_runs
    FOR EACH STATEMENT EXECUTE FUNCTION tracelab.refuse_change();

CREATE TABLE tracelab.lab_frontend_events (
    id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id   uuid,
    user_id           uuid        NOT NULL,
    email             text        CHECK (email IS NULL OR char_length(email) <= 320),
    kind              text        NOT NULL CHECK (kind IN ('answer_shown','error','stopped')),
    turn_id           text        CHECK (turn_id IS NULL OR char_length(turn_id) BETWEEN 1 AND 200),
    session_id        text        CHECK (session_id IS NULL OR char_length(session_id) <= 200),
    question          text        CHECK (question IS NULL OR char_length(question) <= 4000),
    view              text        CHECK (view IS NULL OR char_length(view) <= 60),
    instance          text        CHECK (instance IS NULL OR char_length(instance) <= 40),
    ms_first_text     integer     CHECK (ms_first_text IS NULL OR ms_first_text BETWEEN 0 AND 86400000),
    ms_total          integer     CHECK (ms_total IS NULL OR ms_total BETWEEN 0 AND 86400000),
    error             text        CHECK (error IS NULL OR char_length(error) <= 500),
    client_at         timestamptz,
    created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_tl_lab_frontend_events_turn ON tracelab.lab_frontend_events (turn_id);

CREATE INDEX ix_tl_lab_frontend_events_org ON tracelab.lab_frontend_events (organization_id, created_at DESC);

CREATE INDEX ix_tl_lab_frontend_events_user ON tracelab.lab_frontend_events (user_id, created_at DESC);

CREATE TRIGGER lab_frontend_events_append_only BEFORE UPDATE OR DELETE ON tracelab.lab_frontend_events
    FOR EACH ROW EXECUTE FUNCTION tracelab.refuse_change();

CREATE TRIGGER lab_frontend_events_no_truncate BEFORE TRUNCATE ON tracelab.lab_frontend_events
    FOR EACH STATEMENT EXECUTE FUNCTION tracelab.refuse_change();

COMMENT ON TABLE tracelab.lab_reviews IS 'A person decision on a proposal of a coding agent: a failure mode version, an expected answer or a specification version. One final decision per proposal.';

COMMENT ON TABLE tracelab.lab_spec_versions IS 'Versions of the answer specification (SPEC.md): numbered rules, each tied to a failure mode. The newest approved version is the specification in force.';

COMMENT ON TABLE tracelab.lab_corrections IS 'The prompt, skill, code or data change made for a failure mode or a specification rule: a commit, a pull request or a file.';

COMMENT ON TABLE tracelab.lab_regression_runs IS 'A run made to check one failure mode: the questions people marked positive for it, asked again after a correction.';

COMMENT ON TABLE tracelab.lab_frontend_events IS 'What the browser saw of an answer: when its text first showed, when it finished, or the error the person saw.';
