-- 0012_scenarios.sql: synthetic batches that are ASKED but not graded. A scenario run generates questions for one
-- instance (agents/spaces.py: ops, comp, assets, full), asks each one through the real chat, and keeps what came back
-- -- the question, the answer, the tool sequence in the order the tools were called, the models, the trace turn, the
-- instance and the time. There is no expected answer and no grade: an expected answer has to be grounded in a real row
-- and read by a person, and one invented by a model would make an evaluation set agree with itself. The golden tables
-- stay the place for graded work; these are the place for "what does it actually say".
--
-- Why a table at all: /scenarios/run has returned its results to the caller and forgotten them since it was built
-- (3 Nov 2026), because tracelab.jobs.kind has a CHECK constraint and there was nowhere to put them. Item 7 of the
-- 30 Oct feedback asks for each question, response, tool sequence, trace, model, instance context and timestamp to be
-- SAVED in Trace Lab, and that is what these two tables are for.
--
-- Append-only like every other table here: the newest row is the current one, a correction is a new row, and a coding
-- agent may INSERT directly. Runs in Trace Lab's OWN database (hoist_tracelab). Applied only by migrate.apply_pending.
-- A correction is a new numbered file.
SET LOCAL lock_timeout = '3s';

CREATE TABLE tracelab.scenario_runs (
    id                uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
    run_no            integer       GENERATED BY DEFAULT AS IDENTITY,
    organization_id   uuid          NOT NULL,
    -- The instance the batch was asked in. It decides which engines may answer at all, so the same questions asked in
    -- two instances are two measurements and must never be read as one.
    space             text          NOT NULL CHECK (space IN ('ops', 'comp', 'assets', 'full')),
    -- Generation is deterministic from (space, seed): the same pair reproduces the batch exactly, which is what lets a
    -- failure be re-run. fingerprint is the twelve hex of the questions, so a run can say which batch it measured.
    seed              integer       NOT NULL CHECK (seed >= 0),
    challenge_ratio   numeric(4,3)  NOT NULL DEFAULT 0 CHECK (challenge_ratio BETWEEN 0 AND 1),
    fingerprint       text          CHECK (fingerprint IS NULL OR fingerprint ~ '^[0-9a-f]{12}$'),
    requested         integer       NOT NULL CHECK (requested >= 0),
    asked             integer       NOT NULL DEFAULT 0 CHECK (asked >= 0),
    status            text          NOT NULL DEFAULT 'done'
                                    CHECK (status IN ('running', 'done', 'failed', 'cancelled')),
    source            text          NOT NULL DEFAULT 'page' CHECK (source IN ('page', 'coding_agent', 'cli')),
    usd_spent         numeric(12,6) NOT NULL DEFAULT 0 CHECK (usd_spent >= 0),
    ms                integer       CHECK (ms IS NULL OR ms >= 0),
    error             text          CHECK (error IS NULL OR length(error) <= 2000),
    started_by        uuid,
    started_by_email  text          CHECK (started_by_email IS NULL OR char_length(started_by_email) <= 320),
    started_at        timestamptz   NOT NULL DEFAULT now(),
    finished_at       timestamptz,
    CONSTRAINT ux_tl_scenario_runs_no UNIQUE (run_no),
    CONSTRAINT ck_tl_scenario_runs_asked CHECK (asked <= requested)
);

CREATE INDEX ix_tl_scenario_runs_org ON tracelab.scenario_runs (organization_id, started_at DESC);
CREATE INDEX ix_tl_scenario_runs_space ON tracelab.scenario_runs (organization_id, space, started_at DESC);

CREATE TRIGGER scenario_runs_append_only BEFORE UPDATE OR DELETE ON tracelab.scenario_runs
    FOR EACH ROW EXECUTE FUNCTION tracelab.refuse_change();

CREATE TRIGGER scenario_runs_no_truncate BEFORE TRUNCATE ON tracelab.scenario_runs
    FOR EACH STATEMENT EXECUTE FUNCTION tracelab.refuse_change();

COMMENT ON TABLE tracelab.scenario_runs IS
    'One synthetic batch, asked through the real chat in one instance and never graded: there is no expected answer. Graded work lives in the golden tables.';
COMMENT ON COLUMN tracelab.scenario_runs.space IS
    'The instance (agents/spaces.py). It decides which engines may answer, so two runs in different instances are two measurements.';
COMMENT ON COLUMN tracelab.scenario_runs.seed IS
    'Generation is deterministic from (space, seed), so the same batch can be produced again to re-run a failure exactly.';
COMMENT ON COLUMN tracelab.scenario_runs.challenge_ratio IS
    'The share of the batch generated OUTSIDE the instance, which it must refuse. A gate that stops working is silent otherwise.';

CREATE TABLE tracelab.scenario_results (
    id                uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
    run_id            uuid          NOT NULL REFERENCES tracelab.scenario_runs (id),
    organization_id   uuid          NOT NULL,
    seq_no            integer       NOT NULL CHECK (seq_no >= 1),
    -- The generator's own code for the question (OPS-1-003), so a result can be matched back to the batch that made it.
    scenario_id       text          NOT NULL CHECK (char_length(scenario_id) BETWEEN 1 AND 64),
    question          text          NOT NULL CHECK (char_length(question) BETWEEN 1 AND 4000),
    answer            text,
    -- Which engine the REAL router sent it to, recorded rather than the pool it was generated from: the two differ,
    -- and what the router did is the fact worth keeping.
    engine            text          CHECK (engine IS NULL OR char_length(engine) <= 64),
    role              text          CHECK (role IS NULL OR char_length(role) <= 64),
    style             text          CHECK (style IS NULL OR char_length(style) <= 64),
    difficulty        text          CHECK (difficulty IS NULL OR char_length(difficulty) <= 64),
    -- A question generated OUTSIDE this instance: it must be refused. The one thing that can be judged here without an
    -- expected answer, and the reason gate_ok is a verdict on the gate rather than on the answer.
    in_module         boolean       NOT NULL DEFAULT true,
    gate_ok           boolean,
    -- The order the tools were called in, which is the part worth reading; a set would lose it.
    tools             jsonb         NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(tools) = 'array'),
    models            jsonb         NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(models) = 'array'),
    spans             integer       CHECK (spans IS NULL OR spans >= 0),
    session_id        text          CHECK (session_id IS NULL OR char_length(session_id) BETWEEN 1 AND 200),
    turn_id           text          CHECK (turn_id IS NULL OR char_length(turn_id) BETWEEN 1 AND 200),
    usd               numeric(12,6) CHECK (usd IS NULL OR usd >= 0),
    ms                integer       CHECK (ms IS NULL OR ms >= 0),
    error             text          CHECK (error IS NULL OR length(error) <= 2000),
    asked_at          timestamptz   NOT NULL DEFAULT now(),
    created_at        timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT ux_tl_scenario_results_seq UNIQUE (run_id, seq_no),
    -- gate_ok is a verdict on a question that had to be refused; it is meaningless for one that did not.
    CONSTRAINT ck_tl_scenario_results_gate CHECK (in_module OR gate_ok IS NOT NULL),
    CONSTRAINT ck_tl_scenario_results_in_module_ungraded CHECK (NOT in_module OR gate_ok IS NULL)
);

CREATE INDEX ix_tl_scenario_results_run ON tracelab.scenario_results (run_id, seq_no);
CREATE INDEX ix_tl_scenario_results_turn ON tracelab.scenario_results (turn_id);
CREATE INDEX ix_tl_scenario_results_org ON tracelab.scenario_results (organization_id, asked_at DESC);
-- The failure worth finding: a question outside its instance that was answered anyway.
CREATE INDEX ix_tl_scenario_results_gate_failed ON tracelab.scenario_results (run_id)
    WHERE gate_ok IS FALSE;

CREATE TRIGGER scenario_results_append_only BEFORE UPDATE OR DELETE ON tracelab.scenario_results
    FOR EACH ROW EXECUTE FUNCTION tracelab.refuse_change();

CREATE TRIGGER scenario_results_no_truncate BEFORE TRUNCATE ON tracelab.scenario_results
    FOR EACH STATEMENT EXECUTE FUNCTION tracelab.refuse_change();

COMMENT ON TABLE tracelab.scenario_results IS
    'One asked question: what was asked, what came back, the tools in the order they were called, the models, the trace turn and when. Never graded.';
COMMENT ON COLUMN tracelab.scenario_results.engine IS
    'Where the real router sent the question, not the pool it was generated from. The two differ, and this is the one that happened.';
COMMENT ON COLUMN tracelab.scenario_results.tools IS
    'The tool sequence, in call order. An array of names, not a set: the order is the part worth reading.';
COMMENT ON COLUMN tracelab.scenario_results.gate_ok IS
    'Only for a question generated outside this instance: true when the instance refused it. NULL for an in-module question, which has no expected answer to judge against.';
COMMENT ON COLUMN tracelab.scenario_results.turn_id IS
    'The chat turn, so the answer can be read beside its spans in Hoist Traces when the turn was recorded.';
