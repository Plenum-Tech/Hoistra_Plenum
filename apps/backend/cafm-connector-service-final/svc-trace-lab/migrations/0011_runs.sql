ALTER TABLE tracelab.step_labels ADD CONSTRAINT ck_tl_step_labels_live CHECK (tombstone OR label IS NOT NULL OR note IS NOT NULL);

ALTER TABLE tracelab.step_labels DROP CONSTRAINT step_labels_reviewer_role_check;

ALTER TABLE tracelab.step_labels ADD CONSTRAINT step_labels_reviewer_role_check
    CHECK (reviewer_role IN ('domain_expert','tester','admin','user','platform','consultant'));

CREATE TABLE tracelab.lab_platform_members (
    id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id           uuid        NOT NULL,
    email             text        CHECK (email IS NULL OR char_length(email) <= 320),
    lab_role          text        NOT NULL CHECK (lab_role IN ('consultant')),
    status            text        NOT NULL CHECK (status IN ('active','removed')),
    decided_by        uuid        NOT NULL,
    decided_by_email  text        CHECK (decided_by_email IS NULL OR char_length(decided_by_email) <= 320),
    created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_tl_platform_members_user ON tracelab.lab_platform_members (user_id, created_at DESC);

CREATE TRIGGER lab_platform_members_append_only BEFORE UPDATE OR DELETE ON tracelab.lab_platform_members
    FOR EACH ROW EXECUTE FUNCTION tracelab.refuse_change();

CREATE TRIGGER lab_platform_members_no_truncate BEFORE TRUNCATE ON tracelab.lab_platform_members
    FOR EACH STATEMENT EXECUTE FUNCTION tracelab.refuse_change();

CREATE TABLE tracelab.lab_runs (
    id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    run_no            integer     GENERATED BY DEFAULT AS IDENTITY,
    kind              text        NOT NULL CHECK (kind IN ('synthetic','production')),
    title             text        NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
    organization_id   uuid,
    owner_user_id     uuid,
    owner_email       text        CHECK (owner_email IS NULL OR char_length(owner_email) <= 320),
    run_day           date,
    source            text        NOT NULL CHECK (source IN ('sync','coding_agent','excel','manual')),
    created_by        uuid,
    created_by_email  text        CHECK (created_by_email IS NULL OR char_length(created_by_email) <= 320),
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ux_tl_lab_runs_no UNIQUE (run_no),
    CONSTRAINT ck_tl_lab_runs_production CHECK (kind <> 'production' OR (owner_user_id IS NOT NULL AND run_day IS NOT NULL))
);

CREATE UNIQUE INDEX ux_tl_lab_runs_user_day ON tracelab.lab_runs
    (owner_user_id, (coalesce(organization_id, '00000000-0000-0000-0000-000000000000'::uuid)), run_day)
    WHERE kind = 'production';

CREATE INDEX ix_tl_lab_runs_org ON tracelab.lab_runs (organization_id, run_no DESC);

CREATE TRIGGER lab_runs_append_only BEFORE UPDATE OR DELETE ON tracelab.lab_runs
    FOR EACH ROW EXECUTE FUNCTION tracelab.refuse_change();

CREATE TRIGGER lab_runs_no_truncate BEFORE TRUNCATE ON tracelab.lab_runs
    FOR EACH STATEMENT EXECUTE FUNCTION tracelab.refuse_change();

CREATE TABLE tracelab.lab_questions (
