CREATE FUNCTION tracelab.question_id(code text) RETURNS uuid
LANGUAGE sql STABLE AS $$
    SELECT q.id
      FROM tracelab.lab_questions q
      JOIN tracelab.lab_runs r ON r.id = q.run_id
     WHERE upper(btrim(code)) = 'R' || r.run_no || '-' || q.seq_no
$$;

COMMENT ON TABLE tracelab.lab_runs IS 'A run: one synthetic batch, or one person on one day of live chat. Its code is R followed by run_no.';

COMMENT ON TABLE tracelab.lab_questions IS 'A question of a run. Its code is the run code, a hyphen and seq_no, for example R3-12.';

COMMENT ON TABLE tracelab.lab_question_traces IS 'Which recorded answers (agent_trace_turns ids) belong to a question. A live question has the one it was synced from.';

COMMENT ON TABLE tracelab.lab_expected_answers IS 'The expected answer of a question, as versions: the newest row is the current one.';

COMMENT ON TABLE tracelab.lab_failure_modes IS 'Failure modes, the columns of the labels view. The newest row of a lineage is the current one, a tombstone retires it.';

COMMENT ON TABLE tracelab.lab_label_cells IS 'Whether a failure mode is present (positive) or absent (negative) in a question, per person: the newest row per question, mode and person is current, a null value clears it.';

COMMENT ON TABLE tracelab.lab_platform_members IS 'Trace Lab roles that span every company, such as the consultant. The newest row per user is current.';

COMMENT ON FUNCTION tracelab.question_id(text) IS 'The question a code such as R3-12 names, or null.';
