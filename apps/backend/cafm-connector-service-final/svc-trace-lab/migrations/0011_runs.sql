-- 0011_runs.sql: runs above questions, with serial codes (runs R1, R2 and questions R1-1, R1-2), the expected answer of
-- each question, failure modes and a per-question positive or negative cell for each, and platform-wide Trace Lab roles
-- (the consultant). A run is a synthetic batch (a coding agent, an Excel import or the page) or one person's live
-- questions on one day. A note may now be free text alone: the Right / Wrong / Not sure tag becomes optional. Every new
-- table is append-only: the newest row for a question, mode, person or lineage is the current one, and a coding agent
-- may INSERT directly (tracelab.question_id turns a code such as R1-12 into the question it names). Runs in Trace Lab's
-- OWN database (hoist_tracelab). Applied only by migrate.apply_pending. A correction is a new numbered file.
SET LOCAL lock_timeout = '3s';

