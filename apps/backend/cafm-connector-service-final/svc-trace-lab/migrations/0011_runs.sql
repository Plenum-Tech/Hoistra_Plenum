    scenario_ref      text        CHECK (scenario_ref IS NULL OR char_length(scenario_ref) BETWEEN 1 AND 200),
    organization_id   uuid,
    asked_at          timestamptz,
    source            text        NOT NULL CHECK (source IN ('sync','coding_agent','excel','manual')),
    created_by        uuid,
    created_by_email  text        CHECK (created_by_email IS NULL OR char_length(created_by_email) <= 320),
    created_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ux_tl_lab_questions_seq UNIQUE (run_id, seq_no)
